#!/usr/bin/env python3
"""Turn FCEUX captures into the stage-one/title C data and optional PNGs."""
import argparse
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# FCEUX 2.6.6's 6-bit RGB expansion, embedded so the repository does not need
# to ship a captured palette file.
FCEUX_RGB = bytes.fromhex(
    '75757524188e0000aa45009e8e0075aa0010a600007d0800412c0000450000'
    '5100003c14183c5d000000000000000000bebebe0071ef2038ef8200f3be00'
    'bee70059db2800cb4d0c8a710000960000aa0000923800828a000000000000'
    '000000ffffff3cbeff5d96ffcf8afff779ffff75b6ff7561ff9a38f3be3c82d3'
    '104ddf4959fb9a00ebdb797979000000000000ffffffaae7ffc7d7ffd7cbff'
    'ffc7ffffc7dbffbeb2ffdbaaffe7a2e3ffa2aaf3beb2ffcf9efff3c7c7c700'
    '0000000000')


def c_array(name, data, width):
    rows = ['    {' + ','.join(str(v) for v in data[i:i + width]) + '}' for i in range(0, len(data), width)]
    return f'static const unsigned char {name}[{len(rows)}][{width}] = {{\n' + ',\n'.join(rows) + '\n};\n'


def export(captures, out, png_dir=None):
    stage = (captures / 'stage1-ppu.bin').read_bytes()
    title = (captures / 'title-ppu.bin').read_bytes()
    tiles = b''.join(stage[0x2000 + (y + 2) * 32 + 2:0x2000 + (y + 2) * 32 + 28] for y in range(26))
    if set(tiles) - {0, 15, 16, 32, 200, 201, 202, 203} or tiles.count(15) != 220:
        raise ValueError('Capture is not the intact first stage; inspect the emulator output')
    text = '// Generated by tools/export_reference.py from FCEUX frame 1300.\n'
    text += '#ifndef BATTLECITY_STAGE1_H\n#define BATTLECITY_STAGE1_H\n'
    text += c_array('stage1_tiles', tiles, 26)
    text += c_array('stage1_background', stage[0x2000:0x23c0], 32)
    text += c_array('stage1_attributes', stage[0x23c0:0x2400], 8)
    text += c_array('title_tiles', title[0x2800:0x2bc0], 32)
    text += c_array('title_attributes', title[0x2bc0:0x2c00], 8)
    text += c_array('reference_palettes', stage[0x3f00:0x3f20], 4)
    text += c_array('title_palettes', title[0x3f00:0x3f20], 4)
    # The ROM uses 8x16 sprites; $0200 is its OAM shadow in these captures.
    ram = (captures / 'title-ram.bin').read_bytes()
    cursor = b''.join(ram[i:i + 4] for i in range(0x200, 0x300, 4) if ram[i] < 239)
    text += c_array('title_sprites', cursor, 4)
    if len(FCEUX_RGB) != 192:
        raise ValueError('Expected a 64-color RGB palette')
    text += 'static const uint32_t reference_rgb[64] = {\n'
    for row in range(0, 64, 8):
        text += '    ' + ','.join('0x' + FCEUX_RGB[i * 3:i * 3 + 3].hex() for i in range(row, row + 8)) + ',\n'
    text += '};\n'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text + '#endif\n')
    if png_dir is None:
        print(f'Wrote {out}')
        return
    png_dir.mkdir(parents=True, exist_ok=True)
    for name in ('stage1', 'title'):
        if not (captures / f'{name}.gd').exists():
            continue
        gd = (captures / f'{name}.gd').read_bytes()
        if gd[:7] != bytes.fromhex('ff fe 01 00 00 f0 01') or len(gd) != 11 + 256 * 240 * 4:
            raise ValueError('Unexpected GD truecolor screenshot format')
        rgb = b''.join(gd[i + 1:i + 4] for i in range(11, len(gd), 4))
        def chunk(kind, data):
            return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))
        scan = b''.join(b'\0' + rgb[y * 768:(y + 1) * 768] for y in range(240))
        png = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', 256, 240, 8, 2, 0, 0, 0))
        (png_dir / f'{name}.png').write_bytes(png + chunk(b'IDAT', zlib.compress(scan)) + chunk(b'IEND', b''))
    print(f'Exported {out} and PNGs in {png_dir}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--captures', required=True, type=Path,
                        help='directory containing title/stage1 FCEUX captures')
    parser.add_argument('--out', required=True, type=Path,
                        help='output path for stage1.h')
    parser.add_argument('--png-dir', type=Path, default=None,
                        help='optional directory for title.png/stage1.png')
    args = parser.parse_args()
    export(args.captures, args.out, args.png_dir)


if __name__ == '__main__':
    main()
