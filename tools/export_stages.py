#!/usr/bin/env python3
"""Export the Famicom ROM's 35 stage layouts and enemy tables to C.

The data lives in PRG at the addresses documented by the reverse-engineering
notes: StageDataTable at $F07A (CPU) and the per-stage enemy rows at
$E4EC/$E578.  Each stage row is 13x13 nibbles packed into 7 bytes per row.
"""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXPECTED_SHA256 = 'a869aead5b6957fc62002ff9636e048cc34baf0100d629b07dc51aa18f220c0c'
STAGE_COUNT = 35
STAGE_STRIDE = 91

# CPU address $F07A maps to PRG offset $307A in this 16 KiB NROM image.
STAGE_TABLE = 0x307A
ENEMY_TYPE_TABLE = 0x24EC
ENEMY_COUNT_TABLE = 0x2578


def read_rom(rom_path):
    data = Path(rom_path).read_bytes()
    if hashlib.sha256(data).hexdigest() != EXPECTED_SHA256:
        raise ValueError('Unexpected ROM hash; stage table offsets are version-specific')
    if data[:4] != b'NES\x1a' or data[4] != 1 or data[5] != 1:
        raise ValueError('Expected a mapper-0 iNES ROM with 16 KiB PRG')
    prg = data[16:16 + 16384]
    if len(prg) != 16384:
        raise ValueError('ROM is truncated')
    return prg


def decode_stage(prg, stage):
    data = prg[STAGE_TABLE + stage * STAGE_STRIDE:
               STAGE_TABLE + (stage + 1) * STAGE_STRIDE]
    if len(data) != STAGE_STRIDE:
        raise ValueError(f'Stage {stage + 1} is truncated')
    rows = []
    for row in range(13):
        packed = data[row * 7:row * 7 + 7]
        nibbles = []
        for byte in packed:
            nibbles.extend((byte >> 4, byte & 0x0f))
        if any(value > 0x0f for value in nibbles[:13]):
            raise ValueError('Invalid stage nibble')
        rows.append(nibbles[:13])
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--rom', required=True, type=Path,
                        help='path to the user-supplied Battle City iNES ROM')
    parser.add_argument('--out', required=True, type=Path,
                        help='output directory for stages.h')
    args = parser.parse_args()
    prg = read_rom(args.rom)
    stage_rows = []
    for stage in range(STAGE_COUNT):
        stage_rows.append(decode_stage(prg, stage))

    types = [[prg[ENEMY_TYPE_TABLE + stage * 4 + kind] >> 4
              for kind in range(4)] for stage in range(STAGE_COUNT)]
    counts = [list(prg[ENEMY_COUNT_TABLE + stage * 4:
                      ENEMY_COUNT_TABLE + (stage + 1) * 4])
              for stage in range(STAGE_COUNT)]
    for stage, row in enumerate(counts):
        if sum(row) != 20:
            raise ValueError(f'Stage {stage + 1} enemy count is not 20')
    for stage, row in enumerate(types):
        if any(value not in (8, 0xa, 0xc, 0xe) for value in row):
            raise ValueError(f'Stage {stage + 1} has an invalid enemy type')

    text = ['// Generated by tools/export_stages.py from BattleCity.nes.',
            '// Stage layouts: PRG $F07A. Enemy composition: $E4EC/$E578.',
            '#ifndef BATTLECITY_STAGES_H',
            '#define BATTLECITY_STAGES_H',
            '',
            f'enum {{ STAGE_COUNT = {STAGE_COUNT} }};',
            '',
            '// One nibble per 16x16 block: 0-3 partial brick, 4 full brick,',
            '// 5-8 partial steel, 9 full steel, A water, B forest, C ice,',
            '// D-F empty. The eagle and its brick wall are placed at runtime.',
            'static const unsigned char stage_blocks[STAGE_COUNT][13][13] = {']
    for stage, rows in enumerate(stage_rows):
        text.append(f'    {{ // stage {stage + 1}')
        for row in rows:
            text.append('        {' + ','.join(f'0x{value:x}' for value in row) + '},')
        text.append('    },')
    text.append('};')
    text.append('')
    text.append('// Kind index for each of the four spawn-type slots.')
    text.append('static const unsigned char stage_enemy_types[STAGE_COUNT][4] = {')
    for row in types:
        text.append('    {' + ','.join(f'0x{value:x}' for value in row) + '},')
    text.append('};')
    text.append('')
    text.append('// Number of tanks of each kind; each row sums to 20.')
    text.append('static const unsigned char stage_enemy_counts[STAGE_COUNT][4] = {')
    for row in counts:
        text.append('    {' + ','.join(str(value) for value in row) + '},')
    text.append('};')
    text.append('')
    text.append('#endif')
    args.out.mkdir(parents=True, exist_ok=True)
    out=args.out / 'stages.h'
    out.write_text('\n'.join(text) + '\n')
    print(f'Wrote {out}: {STAGE_COUNT} stages')


if __name__ == '__main__':
    main()
