#!/usr/bin/env python3
"""Turn the captured brick GAME OVER PPU state into C arrays."""
import argparse
from pathlib import Path

GAME_ROWS = (9, 10, 11, 12)
OVER_ROWS = (15, 16, 17, 18)


def c_array(name, data, width, rows):
    lines = []
    for row in range(rows):
        start = row * width
        lines.append('    {' + ','.join(f'0x{v:02x}' for v in data[start:start + width]) + '},')
    return f'static const unsigned char {name}[{rows}][{width}] = {{\n' + '\n'.join(lines) + '\n};\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ppu', required=True, type=Path,
                        help='GAME OVER PPU snapshot captured by FCEUX')
    parser.add_argument('--out', required=True, type=Path,
                        help='output path for gameover_screen.h')
    args = parser.parse_args()
    data = args.ppu.read_bytes()
    if len(data) != 0x4000:
        raise ValueError('Expected a 16 KiB PPU address-space snapshot')
    tiles = data[0x2000:0x23c0]
    attrs = data[0x23c0:0x2400]
    palettes = data[0x3f00:0x3f20]
    for row in GAME_ROWS + OVER_ROWS:
        if not any(tiles[row * 32:row * 32 + 32]):
            raise ValueError(f'Capture is missing GAME OVER row {row}')
    for row in (0, 1, 8, 13, 14, 19, 29):
        if any(tiles[row * 32:row * 32 + 32]):
            raise ValueError(f'Unexpected tile data in row {row}')
    if any(attrs):
        raise ValueError('GAME OVER screen should use palette 0 everywhere')
    text = f'// Generated by tools/export_gameover.py from {args.ppu.name}.\n'
    text += '#ifndef BATTLECITY_GAMEOVER_SCREEN_H\n#define BATTLECITY_GAMEOVER_SCREEN_H\n'
    text += c_array('gameover_tiles', tiles, 32, 30)
    text += c_array('gameover_attributes', attrs, 8, 8)
    text += c_array('gameover_palettes', palettes, 4, 8)
    text += '#endif\n'
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f'Wrote {args.out}')


if __name__ == '__main__':
    main()
