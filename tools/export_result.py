#!/usr/bin/env python3
"""Turn the captured result-screen PPU snapshot into C arrays."""
import argparse
from pathlib import Path


def c_array(name, data, width, rows):
    lines = []
    for row in range(rows):
        start = row * width
        lines.append('    {' + ','.join(f'0x{v:02x}' for v in data[start:start + width]) + '},')
    return f'static const unsigned char {name}[{rows}][{width}] = {{\n' + '\n'.join(lines) + '\n};\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ppu', required=True, type=Path,
                        help='result-screen PPU snapshot captured by FCEUX')
    parser.add_argument('--out', required=True, type=Path,
                        help='output path for result_screen.h')
    args = parser.parse_args()
    data = args.ppu.read_bytes()
    if len(data) != 0x4000:
        raise ValueError('Expected a 16 KiB PPU address-space snapshot')
    # The Famicom writes the result screen into nametable $2800.
    tiles = data[0x2800:0x2bc0]
    attrs = data[0x2bc0:0x2c00]
    palettes = data[0x3f00:0x3f20]
    if tiles.count(0) < 500 or b'STAGE' != bytes(tiles[5 * 32 + 12:5 * 32 + 17]):
        raise ValueError('Capture is not the static result screen')
    text = f'// Generated by tools/export_result.py from {args.ppu.name}.\n'
    text += '#ifndef BATTLECITY_RESULT_SCREEN_H\n#define BATTLECITY_RESULT_SCREEN_H\n'
    text += c_array('result_tiles', tiles, 32, 30)
    text += c_array('result_attributes', attrs, 8, 8)
    text += c_array('result_palettes', palettes, 4, 8)
    text += '#endif\n'
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text)
    print(f'Wrote {args.out}')


if __name__ == '__main__':
    main()
